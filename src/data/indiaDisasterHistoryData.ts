export interface DisasterHistorySummaryMetrics {
  totalIncidents: number;
  affectedStatesCount: number;
  affectedDistrictsCount: number;
  deathsConfirmed: number;
  deathsProvisional: number;
  totalDeathsCombined: number;
  totalInjuredConfirmed: number;
  totalMissing: number;
  totalRescued: number;
  totalEvacuated: number;
  activeCount: number;
  rescueInProgressCount: number;
  containedCount: number;
  reliefOpsCount: number;
  resolvedCount: number;
  totalActiveOrUnderway: number;
}

export function calculateDisasterHistorySummary(
  incidents: NationalDisasterIncident[]
): DisasterHistorySummaryMetrics {
  const statesSet = new Set<string>();
  const districtsSet = new Set<string>();

  let deathsConfirmed = 0;
  let deathsProvisional = 0;
  let totalInjuredConfirmed = 0;
  let totalMissing = 0;
  let totalRescued = 0;
  let totalEvacuated = 0;

  let activeCount = 0;
  let rescueInProgressCount = 0;
  let containedCount = 0;
  let reliefOpsCount = 0;
  let resolvedCount = 0;

  for (const inc of incidents) {
    if (inc.state) statesSet.add(inc.state);
    if (inc.district) districtsSet.add(`${inc.state}::${inc.district}`);

    if (typeof inc.humanImpact?.deathsConfirmed === 'number') {
      deathsConfirmed += inc.humanImpact.deathsConfirmed;
    }
    if (typeof inc.humanImpact?.deathsProvisional === 'number') {
      deathsProvisional += inc.humanImpact.deathsProvisional;
    }
    if (typeof inc.humanImpact?.injuredConfirmed === 'number') {
      totalInjuredConfirmed += inc.humanImpact.injuredConfirmed;
    }
    if (typeof inc.humanImpact?.missing === 'number') {
      totalMissing += inc.humanImpact.missing;
    }
    if (typeof inc.humanImpact?.rescued === 'number') {
      totalRescued += inc.humanImpact.rescued;
    }
    if (typeof inc.humanImpact?.evacuated === 'number') {
      totalEvacuated += inc.humanImpact.evacuated;
    }

    switch (inc.status) {
      case 'Active':
        activeCount++;
        break;
      case 'Rescue in Progress':
        rescueInProgressCount++;
        break;
      case 'Contained':
        containedCount++;
        break;
      case 'Relief Operations':
        reliefOpsCount++;
        break;
      case 'Resolved':
        resolvedCount++;
        break;
    }
  }

  return {
    totalIncidents: incidents.length,
    affectedStatesCount: statesSet.size,
    affectedDistrictsCount: districtsSet.size,
    deathsConfirmed,
    deathsProvisional,
    totalDeathsCombined: deathsConfirmed + deathsProvisional,
    totalInjuredConfirmed,
    totalMissing,
    totalRescued,
    totalEvacuated,
    activeCount,
    rescueInProgressCount,
    containedCount,
    reliefOpsCount,
    resolvedCount,
    totalActiveOrUnderway: activeCount + rescueInProgressCount + reliefOpsCount,
  };
}

export interface DisasterFilters {
  searchTerm: string;
  state: string; // 'all' or state name
  category: string; // 'all' or category id
  severity: string; // 'all' or severity name
  status: string; // 'all' or status name
  startDate: string; // ISO date string YYYY-MM-DD
  endDate: string; // ISO date string YYYY-MM-DD
  sortBy: 'date_desc' | 'date_asc' | 'severity' | 'casualties';
}

export function filterDisasterRecords(
  incidents: NationalDisasterIncident[],
  filters: DisasterFilters
): NationalDisasterIncident[] {
  const filtered = incidents.filter((inc) => {
    // 1. Search term match (title, locality, district, state, shortDescription)
    if (filters.searchTerm) {
      const q = filters.searchTerm.toLowerCase();
      const match =
        inc.title.toLowerCase().includes(q) ||
        inc.state.toLowerCase().includes(q) ||
        inc.district.toLowerCase().includes(q) ||
        (inc.locality && inc.locality.toLowerCase().includes(q)) ||
        inc.shortDescription.toLowerCase().includes(q) ||
        inc.categoryLabel.toLowerCase().includes(q) ||
        inc.id.toLowerCase().includes(q);
      if (!match) return false;
    }

    // 2. State filter
    if (filters.state && filters.state !== 'all') {
      if (inc.state !== filters.state) return false;
    }

    // 3. Category filter
    if (filters.category && filters.category !== 'all') {
      if (inc.category !== filters.category) return false;
    }

    // 4. Severity filter
    if (filters.severity && filters.severity !== 'all') {
      if (inc.severity !== filters.severity) return false;
    }

    // 5. Status filter
    if (filters.status && filters.status !== 'all') {
      if (inc.status !== filters.status) return false;
    }

    // 6. Date range filter
    if (filters.startDate) {
      if (inc.incidentDate < filters.startDate) return false;
    }
    if (filters.endDate) {
      if (inc.incidentDate > filters.endDate) return false;
    }

    return true;
  });

  // Sorting
  const severityRank: Record<DisasterSeverity, number> = {
    Critical: 4,
    Severe: 3,
    Moderate: 2,
    Minor: 1,
  };

  filtered.sort((a, b) => {
    if (filters.sortBy === 'date_desc') {
      return b.incidentDate.localeCompare(a.incidentDate);
    }
    if (filters.sortBy === 'date_asc') {
      return a.incidentDate.localeCompare(b.incidentDate);
    }
    if (filters.sortBy === 'severity') {
      return severityRank[b.severity] - severityRank[a.severity];
    }
    if (filters.sortBy === 'casualties') {
      const casA = (a.humanImpact.deathsConfirmed || 0) + (a.humanImpact.injuredConfirmed || 0);
      const casB = (b.humanImpact.deathsConfirmed || 0) + (b.humanImpact.injuredConfirmed || 0);
      return casB - casA;
    }
    return 0;
  });

  return filtered;
}
